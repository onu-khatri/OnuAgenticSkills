import fs from 'node:fs';
import path from 'node:path';
import { resolveLocation } from './agents.js';

const AGENTS_BEGIN = '<!-- BEGIN onu-agentic-workshop:agents -->';
const AGENTS_END = '<!-- END onu-agentic-workshop:agents -->';
const INSTRUCTIONS_BEGIN = '<!-- BEGIN onu-agentic-workshop:instructions -->';
const INSTRUCTIONS_END = '<!-- END onu-agentic-workshop:instructions -->';

const AUTO_GENERATED = '<!-- Auto-generated by onu-agentic-workshop. Do not edit between the markers; this section is regenerated on install. -->';

function buildAgentsBlock(agents) {
  const lines = agents.map((agent) => `- **${agent.name}** — ${agent.description}`);
  return [
    AGENTS_BEGIN,
    AUTO_GENERATED,
    '## onu-agentic-workshop agents',
    '',
    ...lines,
    AGENTS_END,
    '',
  ].join('\n');
}

function buildInstructionsBlock(content) {
  return [
    INSTRUCTIONS_BEGIN,
    AUTO_GENERATED,
    '',
    content.trim(),
    INSTRUCTIONS_END,
    '',
  ].join('\n');
}

export function instructionTargets(clients, scope, cwd, formats) {
  const targets = new Map();
  for (const client of clients) {
    const vendor = formats.vendors[client];
    if (!vendor?.instructions) continue;
    const location = vendor.instructions[scope === 'project' ? 'project' : 'user'];
    if (!location) continue;
    const file = resolveLocation(location, cwd);
    if (!targets.has(file)) targets.set(file, vendor.label);
  }
  return [...targets.entries()].map(([file, label]) => ({ file, label }));
}

function applyMarkedSection(file, block, begin, end) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const start = existing.indexOf(begin);
  const stop = existing.indexOf(end);

  let next;
  if (start !== -1 && stop !== -1) {
    next = existing.slice(0, start) + block + existing.slice(stop + end.length);
  } else {
    const separator = existing.trimEnd() ? '\n\n' : '';
    next = `${existing.trimEnd()}${separator}${block}`;
  }

  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next);
}

export function registerAgents(targets, agents, dryRun) {
  const block = buildAgentsBlock(agents);
  for (const target of targets) {
    if (dryRun) {
      console.log(`[dry-run] register agents -> ${target.file}`);
      continue;
    }
    applyMarkedSection(target.file, block, AGENTS_BEGIN, AGENTS_END);
    console.log(`Registered agents -> ${target.file}`);
  }
}

export function registerInstructions(targets, content, dryRun) {
  const block = buildInstructionsBlock(content);
  for (const target of targets) {
    if (dryRun) {
      console.log(`[dry-run] register instructions -> ${target.file}`);
      continue;
    }
    applyMarkedSection(target.file, block, INSTRUCTIONS_BEGIN, INSTRUCTIONS_END);
    console.log(`Registered instructions -> ${target.file}`);
  }
}
